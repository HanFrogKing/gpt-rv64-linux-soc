#!/usr/bin/env python3
"""Validate imported source bytes, overlays, build closure, links and publication hygiene."""
from pathlib import Path
import hashlib,json,re,sys
ROOT=Path(__file__).resolve().parents[1]
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def need(ok,msg):
 if not ok:raise RuntimeError(msg)
manifest=json.loads((ROOT/'provenance/source-import.json').read_text())
for item in manifest['files']:
 p=ROOT/item['path'];need(p.is_file(),'Missing imported source: '+item['path'])
 # Redacted reference recipes are explicitly listed, not silently called exact copies.
 changed=json.loads((ROOT/'provenance/publication-adaptations.json').read_text())
 if item['path'] not in changed['modified_reference_paths']:
  need(sha(p)==item['sha256'],'Imported source hash mismatch: '+item['path'])
pins=json.loads((ROOT/'software/linux/overlay.lock.json').read_text())
for n,h in pins.items():need(sha(ROOT/'software/linux/overlay'/n)==h,'Kernel overlay hash mismatch '+n)
board=ROOT/'fpga/rk-zynq7020-f';script=(board/'scripts/build.tcl').read_text()
paths=re.findall(r'\$(root|repo)/([A-Za-z0-9_./-]+\.(?:sv|vi|v|xdc|bd|tcl))(?![A-Za-z0-9_./-])',script)
need(len(paths)>=50,'Unexpectedly small board build source list')
for kind,n in paths:
 if n.startswith(('reports/','build/')):continue  # Paths generated by Vivado, not source inputs.
 need(((board if kind=='root' else ROOT)/n).is_file(),'Missing build input '+n)
core=(ROOT/'rtl/rv64/seip/rv64_dual_core.sv').read_text()
need('ENABLE_BP&&!ENABLE_C' in core and 'pair_allowed=!ENABLE_C' in core,'GC configuration assumptions changed; review documentation')
need('.ENABLE_C(1)' in (ROOT/'rtl/rv64/board/rv64_board_system_video.sv').read_text(),'Board CPU profile changed')
for p in ROOT.rglob('*'):
 if not p.is_file() or any(x in p.relative_to(ROOT).parts for x in ['.git','build','downloads','__pycache__']):continue
 need(p.stat().st_size<10*1024**2,'Unexpected large file '+str(p.relative_to(ROOT)))
 if p.suffix=='.png':continue
 text=p.read_text(encoding='utf-8')
 need(not re.search(r'(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{40,}|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----)',text),'Possible secret in '+str(p.relative_to(ROOT)))
 need(not re.search(r'(?:[A-Z]:[/\\]Users[/\\][A-Za-z0-9_.-]+|\/home\/[A-Za-z0-9_.-]+|\/mnt\/[a-z]\/Users\/[A-Za-z0-9_.-]+)',text),'Private machine path in '+str(p.relative_to(ROOT)))
 if p.suffix=='.md':
  for target in re.findall(r'\]\(([^)]+)\)',text):
   if '://' in target or target.startswith('#'):continue
   target=target.split('#')[0]
   need((p.parent/target).exists(),'Broken documentation link '+str(p.relative_to(ROOT))+': '+target)
print('PUBLIC_SOURCE_CHECK_PASS',len(manifest['files']),'import pins;',len(pins),'kernel overlay pins;',len(paths),'board input references')
